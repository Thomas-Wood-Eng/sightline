import sys, time; sys.path.insert(0, 'C:/Projects/paypal_hackathon/qa/sr')
from helpers2 import *
TOKEN = 'IkNCYS00ZF90TThyVG5Mb0NVUEdJQmci.t0oL2QHmTZ-rtqy1Y-C49ZMNQGA'
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    ctx = b.new_context(viewport={'width': 1280, 'height': 900}, storage_state=STATE)
    ctx.add_init_script(INIT)
    page = ctx.new_page()
    run = Run('stage5c')
    page.goto(BASE + '/'); page.wait_for_timeout(800); run.collect(page)
    run.mark('5e approve by keyboard')
    ap = ctx.new_page(); ap.goto(BASE + '/approve/' + TOKEN); ap.bring_to_front(); ap.wait_for_timeout(400)
    ap.keyboard.press('Tab'); print('focus:', ap.evaluate("() => document.activeElement.textContent"))
    ap.keyboard.press('Enter'); ap.wait_for_timeout(1500)
    print('approval page after Enter:', ap.evaluate("() => document.body.innerText").replace('\n',' / ')[:300])
    run.mark('5f main tab: confirm, PIN')
    page.bring_to_front(); page.wait_for_timeout(400)
    print('main focus before:', active(page)[:100])
    send_cmd(page, run, 'confirm', pace=2)
    print('pin focused?', active(page)[:120])
    before = turns(page)
    page.keyboard.type('1234'); page.keyboard.press('Enter')
    wait_reply(page, before, timeout=40000)
    run.collect(page)
    time.sleep(12); run.collect(page)
    last = page.evaluate("() => { const t = document.querySelectorAll('#log .turn'); return t[t.length-1].innerText; }")
    print('LAST:', last.replace('\n',' / '))
    ctx.storage_state(path=STATE); run.save(); b.close()

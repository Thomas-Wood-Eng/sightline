import sys, time, json; sys.path.insert(0, 'C:/Projects/paypal_hackathon/qa/sr')
from helpers2 import *
def srv(page): return page.evaluate("async () => { const s = await (await fetch('/api/settings')).json(); return [s.state, s.due_in, s.pay]; }")
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    ctx = b.new_context(viewport={'width': 1280, 'height': 900}, storage_state=STATE)
    ctx.add_init_script(INIT)
    page = ctx.new_page()
    run = Run('stage6e')
    page.goto(BASE + '/'); page.wait_for_timeout(800); run.collect(page)
    print('SERVER before Escape:', srv(page))
    run.mark('6k Escape with a hold on awaiting_confirm')
    page.keyboard.press('Escape'); time.sleep(2); run.collect(page)
    print('SERVER after Escape:', srv(page), '| focus', active(page)[:70])
    print('pay-status:', page.evaluate("() => document.getElementById('pay-status').textContent"))
    run.mark('6l Escape with nothing held')
    page.keyboard.press('Escape'); time.sleep(1.5); run.collect(page)
    print('SERVER after 2nd Escape:', srv(page), '| turns:', turns(page))
    ctx.storage_state(path=STATE); run.save(); b.close()

import sys, time; sys.path.insert(0, 'C:/Projects/paypal_hackathon/qa/sr')
from helpers2 import *
def lastturn(page): return page.evaluate("() => { const t=document.querySelectorAll('#log .turn'); return t.length ? t[t.length-1].innerText : '' }").replace('\n',' / ')
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    ctx = b.new_context(viewport={'width': 1280, 'height': 900}, storage_state=STATE)
    ctx.add_init_script(INIT)
    page = ctx.new_page()
    run = Run('stage6b')
    page.goto(BASE + '/'); page.wait_for_timeout(800); run.collect(page)
    send_cmd(page, run, 'warm hoodie under 40', pace=16)
    send_cmd(page, run, 'next', pace=16)
    send_cmd(page, run, 'add it', pace=2)
    send_cmd(page, run, 'medium', pace=2)
    send_cmd(page, run, 'check out', pace=2)
    send_cmd(page, run, 'confirm', pace=2)
    print('PIN form shown:', not page.evaluate("() => document.getElementById('pin-form').hidden"), '| focus:', active(page)[:110])
    run.mark('6e wrong PIN 9999 in PIN box')
    page.keyboard.type('9999'); page.keyboard.press('Enter')
    try: wait_reply(page, turns(page)-1)
    except Exception as e: print('no reply?', e)
    time.sleep(1); run.collect(page)
    print('WRONG PIN reply:', lastturn(page))
    print('focus:', active(page)[:110], '| pin-form hidden:', page.evaluate("() => document.getElementById('pin-form').hidden"))
    run.mark('6f correct PIN, wait out window')
    if page.evaluate("() => document.getElementById('pin-form').hidden") is False:
        before = turns(page); page.keyboard.type('1234'); page.keyboard.press('Enter')
        wait_reply(page, before); run.collect(page)
        print('CORRECT PIN reply:', lastturn(page))
        time.sleep(14); run.collect(page)
        print('AFTER WINDOW:', lastturn(page))
    ctx.storage_state(path=STATE); run.save(); b.close()

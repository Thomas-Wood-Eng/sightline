import sys, time, json; sys.path.insert(0, 'C:/Projects/paypal_hackathon/qa/sr')
from helpers2 import *
def lastturn(page): return page.evaluate("() => { const t=document.querySelectorAll('#log .turn'); return t.length ? t[t.length-1].innerText : '' }").replace('\n',' / ')
def srv(page): return page.evaluate("async () => { const s = await (await fetch('/api/settings')).json(); return [s.state, s.due_in, s.pay]; }")
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    ctx = b.new_context(viewport={'width': 1280, 'height': 900}, storage_state=STATE)
    ctx.add_init_script(INIT)
    page = ctx.new_page()
    run = Run('stage6c')
    page.goto(BASE + '/'); page.wait_for_timeout(800); run.collect(page)
    run.mark('6g empty submit + vague request')
    n = turns(page); page.keyboard.press('Enter'); time.sleep(1.5); run.collect(page)
    print('EMPTY submit turns added:', turns(page)-n, '| focus:', active(page)[:90])
    send_cmd(page, run, 'stuff', pace=16)
    run.mark('6h Escape at random, nothing held')
    page.keyboard.press('Escape'); page.keyboard.press('Escape'); time.sleep(1); run.collect(page)
    print('Escape x2 turns:', turns(page), '| focus', active(page)[:80])
    for t in ['warm hoodie under 40', 'next', 'add it', 'medium']:
        send_cmd(page, run, t, pace=16 if t.startswith('warm') else 2)
    run.mark('6i double submit check out')
    n = turns(page)
    page.keyboard.type('check out'); page.keyboard.press('Enter')
    page.keyboard.type('check out'); page.keyboard.press('Enter')
    time.sleep(8); run.collect(page)
    print('DOUBLE check out turns added:', turns(page)-n)
    for i, t in enumerate(page.evaluate("() => Array.from(document.querySelectorAll('#log .turn')).slice(-3).map(x => x.innerText.replace(/\n/g,' / ').slice(0,160))")): print('  turn:', t)
    print('server state after double:', srv(page))
    run.mark('6j reload mid-checkout')
    page.reload(); page.wait_for_timeout(1200); run.collect(page)
    print('AFTER RELOAD focus:', active(page)[:100], '| log:', page.evaluate("() => document.getElementById('log').innerText.slice(0,120)"))
    print('server state after reload:', srv(page), '| pin-form hidden:', page.evaluate("() => document.getElementById('pin-form').hidden"))
    ctx.storage_state(path=STATE); run.save(); b.close()
